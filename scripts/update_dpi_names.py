"""Regenerate family_wifi/dpi_names.py from unpoller's DPI tables (MIT licensed).

    python scripts/update_dpi_names.py [path-or-url-to-dpi.go]
"""

import re
import sys
import urllib.request
from pathlib import Path

SRC = "https://raw.githubusercontent.com/unpoller/unifi/master/dpi.go"
OUT = Path(__file__).resolve().parent.parent / "family_wifi" / "dpi_names.py"


def parse(go: str, var: str) -> dict[int, str]:
    body = go.split(f"var {var} = DPIMap{{", 1)[1].split("\n}", 1)[0]
    return {int(k): v for k, v in re.findall(r'^\s*(\d+):\s*"((?:[^"\\]|\\.)*)",', body, re.M)}


def main() -> None:
    src = sys.argv[1] if len(sys.argv) > 1 else SRC
    go = urllib.request.urlopen(src).read().decode() if src.startswith("http") else Path(src).read_text()
    cats, apps = parse(go, "DPICats"), parse(go, "DPIApps")
    lines = [
        '"""UniFi traffic identification (DPI) category and app names.',
        "",
        "Generated by scripts/update_dpi_names.py from unpoller/unifi dpi.go",
        "(https://github.com/unpoller/unifi), MIT License,",
        "Copyright (c) 2018-2020 David Newhall II, Copyright (c) 2016 Garrett Bjerkhoel.",
        "App keys are (category << 16) + app id, as UniFi reports them.",
        '"""',
        "",
        "# fmt: off",
        "CATEGORIES = {",
        *[f"    {k}: {v!r}," for k, v in sorted(cats.items())],
        "}",
        "",
        "APPS = {",
        *[f"    {k}: {v!r}," for k, v in sorted(apps.items())],
        "}",
        "# fmt: on",
        "",
    ]
    OUT.write_text("\n".join(lines))
    print(f"wrote {OUT}: {len(cats)} categories, {len(apps)} apps")


if __name__ == "__main__":
    main()
